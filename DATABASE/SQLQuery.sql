USE master;
GO

IF EXISTS (SELECT * FROM sys.databases WHERE name = 'MiniSocialNetwork')
BEGIN
    ALTER DATABASE MiniSocialNetwork SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
    DROP DATABASE MiniSocialNetwork;
END
GO

CREATE DATABASE MiniSocialNetwork;
GO

USE MiniSocialNetwork;
GO

CREATE TABLE Users (
    UserID INT IDENTITY(1,1) PRIMARY KEY,
    Username NVARCHAR(50) NOT NULL,
    Password NVARCHAR(100) NOT NULL,
    FullName NVARCHAR(100),
    Email NVARCHAR(100),
    Avatar NVARCHAR(255),
    AvatarUrl NVARCHAR(255),
    Bio NVARCHAR(MAX),
    CreatedAt DATETIME DEFAULT GETDATE()
);
GO

CREATE TABLE Posts (
    PostID INT IDENTITY(1,1) PRIMARY KEY,
    UserID INT FOREIGN KEY REFERENCES Users(UserID) ON DELETE CASCADE,
    Content NVARCHAR(MAX),
    Image NVARCHAR(255),
    ImageUrl NVARCHAR(255),
    CreatedAt DATETIME DEFAULT GETDATE()
);
GO

CREATE TABLE Comments (
    CommentID INT IDENTITY(1,1) PRIMARY KEY,
    PostID INT FOREIGN KEY REFERENCES Posts(PostID) ON DELETE CASCADE,
    UserID INT FOREIGN KEY REFERENCES Users(UserID) ON DELETE NO ACTION,
    Content NVARCHAR(MAX) NOT NULL,
    CreatedAt DATETIME DEFAULT GETDATE()
);
GO

CREATE TABLE Likes (
    LikeID INT IDENTITY(1,1) PRIMARY KEY,
    PostID INT FOREIGN KEY REFERENCES Posts(PostID) ON DELETE CASCADE,
    UserID INT FOREIGN KEY REFERENCES Users(UserID) ON DELETE NO ACTION,
    ReactionType NVARCHAR(20) DEFAULT 'Like',
    CreatedAt DATETIME DEFAULT GETDATE(),
    CONSTRAINT UQ_UserPost_Like UNIQUE (PostID, UserID)
);
GO

CREATE TABLE Follows (
    FollowID INT IDENTITY(1,1) PRIMARY KEY,
    FollowerId INT FOREIGN KEY REFERENCES Users(UserID) ON DELETE CASCADE,
    FollowingId INT FOREIGN KEY REFERENCES Users(UserID) ON DELETE NO ACTION,
    CreatedAt DATETIME DEFAULT GETDATE(),
    CONSTRAINT UQ_FollowerFollowing UNIQUE (FollowerId, FollowingId)
);
GO

